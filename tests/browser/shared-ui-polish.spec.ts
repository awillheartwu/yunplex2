import { expect, test, type Page } from './fixtures'
const ok = (data: unknown) => ({ code: 0, msg: 'ok', data })
const sources = Array.from({ length: 61 }, (_, index) => ({ id: `polish-${index}`, name: `收藏 ${index + 1}`, type: 'playlist', neteasePlaylistId: index + 1, trackCount: 10, enabled: true, coverUrl: '', lastStatus: 'idle', initializationStatus: 'skipped', createdAt: '2026-09-26', updatedAt: '2026-09-26' }))
async function prepare(page: Page) {
  await page.goto('/login')
  await page.getByLabel('管理员密码', { exact: true }).fill('browser-test-password')
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL('/')
  await page.route('**/api/playlist-sources**', route => {
    const url = new URL(route.request().url())
    const search = url.searchParams.get('search')
    const items = search ? sources.filter(source => source.name.includes(search)) : sources
    return route.fulfill({ json: ok(url.pathname === '/api/playlist-sources' ? items : sources[0]) })
  })
  await page.route('**/api/runs**', route => route.fulfill({ json: ok({ items: [], total: 0 }) }))
}
for (const width of [1440, 320]) {
  test(`shared selection, empty states and pagination stay usable at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: 950 })
    await prepare(page)
    await page.goto('/sync-sources')
    await page.getByRole('button', { name: '列表视图', exact: true }).click()
    await page.getByRole('checkbox', { name: '选择 收藏 1', exact: true }).check()
    const all = page.getByRole('checkbox', { name: '选择全部收藏' })
    await expect(all).toHaveJSProperty('indeterminate', true)
    expect(await all.evaluate(node => getComputedStyle(node, '::before').borderBottomWidth)).toBe('2px')
    await all.check()
    await expect(all).toHaveJSProperty('indeterminate', false)
    await page.getByRole('searchbox', { name: '搜索同步源' }).focus()
    await expect(all).toHaveCSS('box-shadow', 'none')
    await all.uncheck()
    const pager = page.getByRole('navigation', { name: '收藏分页' })
    await pager.getByRole('button', { name: '下一页' }).click()
    await expect(page.getByRole('checkbox', { name: '选择 收藏 61', exact: true })).toBeVisible()
    expect(await pager.evaluate(node => node.scrollWidth <= node.clientWidth)).toBe(true)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.getByRole('searchbox', { name: '搜索同步源' }).fill('不存在的资源')
    await expect(page.getByRole('heading', { name: '没有匹配的收藏' })).toBeVisible()
    await expect(page.getByRole('heading', { name: '还没有收藏歌单' })).toHaveCount(0)
    await page.getByRole('button', { name: '清除筛选', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: '选择 收藏 1', exact: true })).toBeVisible()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath('library-list.png'), fullPage: false, animations: 'disabled' })

    await page.goto('/sync-sources/polish-0')
    await expect(page.locator('h1')).toBeVisible()
    await page.evaluate(() => document.documentElement.style.setProperty('--font-scale', '1.25'))
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.evaluate(() => document.documentElement.style.setProperty('--font-scale', '1'))
    await page.goto('/logs')
    const active = page.locator('.system-logs-panel__filters').getByRole('button', { name: '全部', exact: true })
    await page.getByRole('heading', { name: '运行日志', exact: true }).hover()
    const normal = await active.evaluate(async node => { await Promise.all(node.getAnimations().map(animation => animation.finished)); return getComputedStyle(node).borderColor })
    await active.hover()
    await expect(active).toHaveCSS('border-color', normal)
    await expect(page.locator('.empty-state__icon')).toHaveCSS('width', '48px')
  })
}
